// Builds writeout/poolside-embed.css from waterflow/poolside-keydown.css (run: node scripts/build_poolside_embed.mjs).
// Waterflow's Poolside Keydown styles are scoped to its own page; this copy is scoped to a `;;pk{ ... }` block (.kd-pk) wherever
// Keydown Next draws one (Writeout, Bitbook, Keydown.js). The scope starts with an id-weight :is() so it beats Keydown's own rules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(ROOT, 'waterflow', 'poolside-keydown.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const SCOPE = ':is(#wysiwyg-canvas, .keydown-doc, .kd-doc, body) .kd-pk';
const PAGE = 'body[data-kd="poolside"] :is(#wf-visual, #wf-view)';
const rules = [];
let i = 0;
while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open < 0) break;
    const prelude = src.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; j++; }
    const body = src.slice(open + 1, j - 1).trim();
    i = j;
    if (!prelude || prelude.startsWith('@media')) continue;                   // (print and phone rules belong to the page)
    const sels = prelude.split(/,\s*(?=body\[)/);
    const out = [];
    for (let s of sels) {
        s = s.trim();
        if (!s.startsWith('body[data-kd="poolside"]') || /data-theme/.test(s)) continue;
        if (s.startsWith(PAGE)) out.push(SCOPE + s.slice(PAGE.length));
        else if (s === 'body[data-kd="poolside"]') out.push('.kd-pk');           // the colour variables
    }
    if (!out.length) continue;
    // (the page-sized rules, a pool-tile floor and the text colour, are not wanted on a small block)
    if (out.length === 1 && out[0] === SCOPE) continue;
    rules.push(out.join(',\n') + ' { ' + body.replace(/\s+/g, ' ') + ' }');
}
const head = `/* POOLSIDE KEYDOWN, for ;;pk{ ... } blocks in Writeout, Bitbook and Keydown.js. Generated by scripts/build_poolside_embed.mjs from waterflow/poolside-keydown.css: edit that one and run the script! */
.kd-pk { display: block; margin: 12px 0; padding: 8px 16px; border: 1px solid #bfeaf9; border-radius: 14px; background: #f4fcff; color: #0b3552; }
.kd-pk > :first-child { margin-top: 4px; } .kd-pk > :last-child { margin-bottom: 4px; }
.kdx-pk-inline.kd-pk { display: inline; margin: 0; padding: 0; border: 0; border-radius: 0; background: none; }
`;
fs.writeFileSync(path.join(ROOT, 'writeout', 'poolside-embed.css'), head + rules.join('\n') + '\n');
console.log('Poolside embed styles built! ' + rules.length + ' rules');
