// gen_keydown_rust.mjs: copies Keydown's tables out of writeout/keydown-doc.js into rust/keydown-core/src/tables.rs,
// so the Rust engine always has exactly the same chips, highlights and styles as the JavaScript one!
// Run from the repo root: node scripts/gen_keydown_rust.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let src = fs.readFileSync(path.join(ROOT, 'writeout/keydown-doc.js'), 'utf8');
const marker = '    const BY_CLASS = new Map();';
if (!src.includes(marker)) throw new Error('gen_keydown_rust: marker not found');
src = src.replace(marker, '    root.__kdTables = { TRIGGERS, HL_COLORS, HL_STYLES, AN_STYLES, US_FAMS: Array.from(US_FAMS) };\n' + marker);
const sandbox = { window: {}, document: undefined, console };
sandbox.window = sandbox; sandbox.globalThis = sandbox;
vm.createContext(sandbox);
try { vm.runInContext(src, sandbox, { filename: 'keydown-doc.js' }); } catch (e) { if (!sandbox.__kdTables) console.error(e); }
const T = sandbox.__kdTables;
if (!T) throw new Error('gen_keydown_rust: tables were not captured');
const q = (s) => JSON.stringify(String(s));   // JSON strings are valid Rust string literals for this data (no \u escapes beyond \u0000 range issues)
const rust = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
let out = '// GENERATED by scripts/gen_keydown_rust.mjs from writeout/keydown-doc.js: do not edit by hand!\n\n';
out += 'pub const TRIGGERS: &[(&str, &str, &str, &str)] = &[\n' + T.TRIGGERS.map((t) => `    (${rust(t[0])}, ${rust(t[1])}, ${rust(t[2])}, ${rust(t[3])}),`).join('\n') + '\n];\n\n';
out += 'pub const HL_COLORS: &[(&str, &str)] = &[' + T.HL_COLORS.map((c) => `(${rust(c[0])}, ${rust(c[1])})`).join(', ') + '];\n';
out += 'pub const HL_STYLES: &[(&str, &str)] = &[' + T.HL_STYLES.map((c) => `(${rust(c[0])}, ${rust(c[1])})`).join(', ') + '];\n';
out += 'pub const AN_STYLES: &[(&str, &str)] = &[' + T.AN_STYLES.map((c) => `(${rust(c[0])}, ${rust(c[1])})`).join(', ') + '];\n';
out += 'pub const US_FAMS: &[&str] = &[' + T.US_FAMS.map(rust).join(', ') + '];\n';

fs.writeFileSync(path.join(ROOT, 'rust/keydown-core/src/tables.rs'), out);
console.log(`tables.rs: ${T.TRIGGERS.length} triggers, ${T.HL_COLORS.length} colors, ${T.AN_STYLES.length} annotate styles, ${T.US_FAMS.length} unique families`);
